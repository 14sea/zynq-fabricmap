#!/usr/bin/env python3
"""Generate firmware/b4q/b4q_regmap.h from the ONE register table of record, host/b4carrier_regmap.py — so that the
executing side and the host read the same offsets, CTRL bits, STATUS bits, fault codes and words. Held byte-identical to a
fresh generation by tests/test_b4q_firmware.py; the A7 check compares the firmware's ACTUAL accesses (logged by the host
transport) against the RTL decode, not this header against itself."""
from __future__ import annotations

import sys
from pathlib import Path

R = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(R / "host"))
import b4carrier_regmap as rm  # noqa: E402

OUT = R / "firmware/b4q/b4q_regmap.h"


def render() -> str:
    o = ["/* GENERATED by host/b4q_gen_regmap.py from host/b4carrier_regmap.py — do not edit. */", "#ifndef B4Q_REGMAP_H", "#define B4Q_REGMAP_H", ""]
    for name in ("CTRL", "STATUS", "FAULT", "Q_LIVE", "IN_LIVE", "SLOT_READ", "SLOT_ADDR", "WITNESS", "TIMING", "HEARTBEAT", "NONCE_LO", "NONCE_HI",
                 "VARIANT", "STEP_IN", "BASE_STATE", "SLOT_IN_READ"):
        o.append(f"#define B4Q_{name} 0x{getattr(rm, name):04x}u")
    o += [f"#define B4Q_PAYLOAD0 0x{rm.PAYLOAD[0]:04x}u", f"#define B4Q_PAYLOAD_WORDS {len(rm.PAYLOAD)}", f"#define B4Q_TAG0 0x{rm.TAG[0]:04x}u",
          f"#define B4Q_TAG_WORDS {len(rm.TAG)}", f"#define B4Q_KEY0 0x{rm.KEY[0]:04x}u /* the signer principal's window: NEVER written by the application */",
          f"#define B4Q_HW_COMMIT0 0x{rm.HW_COMMIT[0]:04x}u", f"#define B4Q_HW_COMMIT_WORDS {len(rm.HW_COMMIT)}",
          f"#define B4Q_VARIANT_WORD 0x{rm.VARIANT_WORD:08x}u", f"#define B4Q_MECHANISM {rm.MECHANISM}u", ""]
    for name, bit in rm.CTRL_BITS.items():
        o.append(f"#define B4Q_CTRL_{name.upper()} (1u << {bit})")
    o.append("")
    for name, bit in rm.STATUS_BITS.items():
        o.append(f"#define B4Q_ST_{name.upper()} {bit}u")
    for name, (b, w) in rm.STATUS_FIELDS.items():
        o.append(f"#define B4Q_ST_{name.upper()}_SHIFT {b}u"); o.append(f"#define B4Q_ST_{name.upper()}_MASK 0x{(1 << w) - 1:x}u")
    o.append("")
    for name, bit in rm.WITNESS_BITS.items():
        o.append(f"#define B4Q_WIT_{name.upper()} {bit}u")
    for name, (b, w) in rm.WITNESS_FIELDS.items():
        o.append(f"#define B4Q_WIT_{name.upper()}_SHIFT {b}u"); o.append(f"#define B4Q_WIT_{name.upper()}_MASK 0x{(1 << w) - 1:x}u")
    o.append("")
    for code, name in sorted(rm.FAULT_CODES.items()):
        o.append(f"#define B4Q_F_{name.upper()} {code}u")
    o += ["", "#endif /* B4Q_REGMAP_H */", ""]
    return "\n".join(o)


def main(argv=None) -> int:
    text = render()
    if argv and "--check" in argv:
        ok = OUT.read_text() == text
        print("b4q_regmap.h", "equal to a fresh generation" if ok else "DIFFERS")
        return 0 if ok else 1
    OUT.write_text(text); print(OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
