#!/usr/bin/env python3
"""Generate firmware/b4q/b4q_data.h (and its JSON sidecar firmware/b4q/b4q_data.json) from the loaded image and the
certificate mapping — the B4 counterpart of the instrument's gen_firmware_data.py. Read-only over its inputs; the header is
held byte-identical to a fresh generation by tests/test_b4q_derive.py."""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

R = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(R / "host"))
import b4q_frames as fr  # noqa: E402

OUT_H = R / "firmware/b4q/b4q_data.h"
OUT_JSON = R / "firmware/b4q/b4q_data.json"


def render(base: dict, wl) -> str:
    rec = fr.write_set_record(base, wl)
    out = ["/* GENERATED by host/b4q_gen_data.py (zynq-fabricmap) — do not edit.",
           " * B4 carrier v2 write set: the eight target frames of two envelopes in the column 0x00400a00 of SLICE_X2Y25 and",
           " * the two flush frames, all from the LOADED IMAGE (the natural build); the 21 whitelisted bits in the mapping's",
           " * address order (bit i of the genome = address i).",
           f" * Source: {fr.BITSTREAM_REL} sha256 {base['bitstream_sha256']}",
           f" * Loaded-image target frames (FAR-ordered hash domain): {rec['loaded_image_target_frames_sha256']}",
           " */", "#ifndef B4Q_DATA_H", "#define B4Q_DATA_H", "#include <stdint.h>", "",
           f"#define P3_IDCODE 0x{fr.IDCODE:08x}u   /* the instrument's names are kept: the derived C unit's verbatim functions read them */", "",
           f"static const uint32_t P3_TARGET_FARS[{len(fr.TARGET_FARS)}] = {{", "    " + ", ".join(f"0x{f:08x}u" for f in fr.TARGET_FARS), "};",
           f"static const uint32_t P3_FLUSH_FARS[{len(fr.FLUSH_FARS)}] = {{", "    " + ", ".join(f"0x{f:08x}u" for f in fr.FLUSH_FARS), "};", "",
           "/* envelope: FAR-set, the four target frames it carries (indices into B4Q_TARGET_FARS), the flush frame that follows (index into B4Q_FLUSH_FARS). */",
           "typedef struct { uint32_t far_set; int target[4]; int flush; } p3_envelope;",
           f"static const p3_envelope P3_ENVELOPE[{len(fr.ENVELOPES)}] = {{"]
    for k, e in enumerate(fr.ENVELOPES):
        idx = ", ".join(str(fr.TARGET_FARS.index(t)) for t in e["targets"])
        out.append(f"    {{ 0x{e['far_set']:08x}u, {{ {idx} }}, {k} }},")
    out += ["};", "", "/* a whitelisted content bit: which target frame, which word, which bit. Index i = bit i of the genome (the mapping's address order). */",
            "typedef struct { uint8_t frame; uint8_t word; uint8_t bit; } p3_address;",
            f"static const p3_address P3_WHITELIST[{len(wl)}] = {{"]
    for far, w, b in wl:
        out.append(f"    {{ {fr.TARGET_FARS.index(far)}, {w}, {b} }},")
    out += ["};", ""]

    def block(name, fars):
        rows = [f"static const uint32_t {name}[{len(fars)}][101] = {{"]
        for far in fars:
            rows.append(f"    {{ /* {far:#010x} */")
            words = base["frames"][far]
            for i in range(0, 101, 6):
                rows.append("        " + " ".join(f"0x{w:08x}u," for w in words[i:i + 6]))
            rows.append("    },")
        rows.append("};")
        return rows
    out += block("P3_BASE_TARGET", fr.TARGET_FARS) + [""] + block("P3_BASE_FLUSH", fr.FLUSH_FARS)
    out += ["", "#endif /* B4Q_DATA_H */", ""]
    return "\n".join(out)


def main(argv=None) -> int:
    base = fr.load_base()
    wl = fr.whitelist()
    text = render(base, wl)
    rec = fr.write_set_record(base, wl)
    rec["header_sha256"] = hashlib.sha256(text.encode()).hexdigest()
    rec["generator"] = "host/b4q_gen_data.py"
    if argv and "--check" in argv:
        ok = OUT_H.read_text() == text and json.loads(OUT_JSON.read_text()) == rec
        print("b4q_data.h and b4q_data.json", "equal to a fresh generation" if ok else "DIFFER from a fresh generation")
        return 0 if ok else 1
    OUT_H.write_text(text)
    OUT_JSON.write_text(json.dumps(rec, indent=1) + "\n")
    print(OUT_H, rec["header_sha256"])
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
