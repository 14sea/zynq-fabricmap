"""b3/host/b3_session.py — the host-only reference orchestrator (lifecycle 2, the session unit).

Held here: the opening and closing blank baselines and the record formula 2 + N × (3 × B + 3); the
six arm orders (RFO, FOR, ORF, ROF, OFR, FRO) and a later slice that keeps the absolute pair index,
that pair's seeds and that pair's arm order (its blocks byte-identical to the full experiment's); B3
and B3Q (the latter through the production plan / prediction builders — 1 pair at budget 40: 120
search + 3 holdout candidates, 40 ledger entries, 125 records with the baselines — accepted by
`b3_records.context_from`, which is what the B3Q plan's `b1_map_cost` was added for); every O-arm
block field for field against the prediction (the ledger entry, the final commitment on the last
search record and on the holdout record) and every arm's best and holdout, the fitness-sequence
digest included; the early stop at every kind of position (the opening baseline, a search, each of
the three holdouts, the closing baseline) — nothing proposed after it and no closing baseline;
illegal inputs (slice, seed count, seed shape, budget, wrong types, any fitness but the preregistered F1 — even a self-consistent F2 context, refused before any arm runs) refused by name; the full
experiment and a later slice accepted by `b3_records.validate_run_log` with no finding; and — after
`run_online` learned to emit record blocks — the committed eight-pair prediction regenerated byte for
byte and reproduced by the session record for record.

The committed-prediction test reads `evidence/b3/plan.json` / `prediction.json` (the canonical
preflight of 7cb0879, pre-S0: no B3 manifest exists yet; the stage-aware coverage of preregistration
§9 arrives with the manifest unit). It is a regression guard on the reference, not a stage assertion.
"""
