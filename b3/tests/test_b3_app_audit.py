def longest_literal() -> int:
    n = 0
    for f in ("b3_app.c", "p3_rectx.c", "p3_pull.c"):
        for m in re.finditer(r'"((?:[^"\\\n]|\\.)*)"', gen.strip_comments((FW / f).read_text())):
            n = max(n, len(m.group(1)))
    return n


def app_macro(name: str) -> int:
    m = re.search(rf"#define {name} (\d+)u", APP)
    assert m, name
    return int(m.group(1))


def frame_types() -> set:
    return set(re.findall(r'(?:build_payload_frame|send_payload|build_frame)\("([A-Z_]+)"', APP))


def sparse_entries() -> int:
    m = re.search(r"static char g_words_b64\[(\d+)\];", APP)
    assert m
    return int(m.group(1)) - 1


def driver() -> dict:
    """Build and run the generated driver once per process; parse its probes and its lines."""
    if "d" in _CACHE:
        return _CACHE["d"]
    cc = os.environ.get("CC", "cc")
    if shutil.which(cc) is None:
        raise AssertionError("no host C compiler: a failure, never a skip")
    BUILD.mkdir(parents=True, exist_ok=True)
    src = BUILD / "bounds_driver.c"
    src.write_text(DRIVER)
    exe = BUILD / "bounds_driver"
    units = [str(FW / u) for u in ("b3_record.c", "b3_carto.c", "b2_search.c", "b3_wire.c", "p3_derive.c")]
    p = subprocess.run([cc, "-std=c99", "-O1", "-w", "-I", str(FW), "-o", str(exe), str(src), *units], capture_output=True, text=True)
    if p.returncode != 0:
        raise AssertionError(f"the bound driver did not build:\n{p.stderr}")
    out = subprocess.run([str(exe), str(longest_literal()), str(sparse_entries()), str(app_macro("B3_LINE_MAX")), TOKEN],
                         capture_output=True, text=True, check=True).stdout
    probes, lines = {}, {}
    for ln in out.split("\n"):
        if not ln:
            continue
        tag, _, rest = ln.partition(" ")
        if tag in ("MAXLINE", "SEQ1LINE"):
            lines[tag] = rest + "\n"
        else:
            probes[tag] = [int(x) for x in rest.split()]
    _CACHE["d"] = {"probes": probes, "lines": lines}
    return _CACHE["d"]


class TheBounds(unittest.TestCase):
    def test_the_declared_bounds_are_the_derived_ones(self):
        d = driver()["probes"]
        block = max(d[t][0] for t in BLOCK_TYPES)
        payload = max(d[t][0] for t in PAYLOAD_TYPES)
        self.assertEqual(block, d["BLOCK_O_SEARCH"][0], "the O search block with its largest ledger is the largest block")
        self.assertEqual(payload, d["REC"][0], "the loop record with that block is the largest payload")
        enc = 4 * math.ceil(payload / 3)
        types = frame_types()
        self.assertEqual(types, set(PAYLOAD_TYPES), "every frame type the application builds is measured")
        line = len("P3L5 ") + max(len(t) for t in types) + 1 + 10 + 1 + 32 + 1 + enc + 1 + 8 + 1
        self.assertEqual(app_macro("B3_SEARCH_BLOCK_MAX"), block + 1)
        self.assertEqual(app_macro("B3_PAYLOAD_MAX"), payload + 1)
        self.assertEqual(app_macro("B3_ENCODED_MAX"), enc + 1)
        self.assertEqual(app_macro("B3_LINE_MAX"), line + 1)
        self.assertGreaterEqual(longest_literal(), 60, "the string bound is the application's longest literal")

    def test_every_encoder_refuses_a_buffer_exactly_its_length_and_renders_in_one_byte_more(self):
        for tag, vals in driver()["probes"].items():
            if tag == "LINECAP":
                continue
            n, exact, plus = vals
            with self.subTest(encoder=tag):
                self.assertGreater(n, 0)
                self.assertEqual(exact, 0, "a buffer exactly the length has no room for the NUL")
                self.assertEqual(plus, n)
        k, refused = driver()["probes"]["LINECAP"]
        self.assertGreater(k, 0, "the longest line fits B3_LINE_MAX")
        self.assertEqual(refused, 0)
        self.assertEqual(k + 1, app_macro("B3_LINE_MAX") - (len("AUDIT_READY") - len("REC")),
                         "the REC line is the bound less the longer frame type's extra bytes")

    def test_every_outbound_and_resend_buffer_is_sized_by_its_bound(self):
        want = {"g_payload": "B3_PAYLOAD_MAX", "g_encoded": "B3_ENCODED_MAX", "g_body": "B3_LINE_MAX", "g_rec_line": "B3_LINE_MAX",
                "g_rec_scratch": "B3_LINE_MAX", "g_tx_line": "B3_LINE_MAX", "g_ready_line": "B3_LINE_MAX",
                "g_search_json": "B3_SEARCH_BLOCK_MAX"}
        for name, macro in want.items():
            with self.subTest(buffer=name):
                self.assertRegex(APP, rf"static char {name}\[{macro}\];", "a static (BSS) buffer of the bound")
        for name in ("g_payload", "g_encoded", "g_body", "g_rec_line", "g_rec_scratch", "g_tx_line", "g_ready_line"):
            self.assertIsNone(re.search(rf"static char {name}\[\d+\]", APP), f"{name}: no hard-coded size")
        calls = re.findall(r"(p3_wire_(?:loop_record|identity|sign_request|summary|audit_ready|audit_sparse|closing|hb|audit_wait))\(", APP)
        self.assertEqual(len(calls), 9)
        self.assertEqual(APP.count("g_payload, sizeof(g_payload)"), 9, "every payload builder is given the payload buffer's own size")
        self.assertIn("b3_orch_record_block(&O, g_search_json, sizeof(g_search_json))", APP)


class TheFailClosedPaths(unittest.TestCase):
    def body(self, signature: str) -> str:
        start = APP.index(signature)
        return APP[start:APP.index("\n}\n", start)]

    def test_base64_is_checked_before_it_runs_and_an_encoder_s_zero_is_protocol(self):
        b = self.body("static size_t build_payload_frame(")
        check = b.index("4u * ((plain_len + 2u) / 3u) + 1u > sizeof(g_encoded)")
        self.assertLess(check, b.index("p3_base64url("), "the capacity check precedes the encoding")
        self.assertIn('p3_stop(P3_PROTOCOL, "PROTOCOL_FRAME: the encoded payload would not fit")', b)
        self.assertIn('p3_stop(P3_PROTOCOL, "PROTOCOL_FRAME: payload builder overflowed")', b)
        self.assertEqual(gen.strip_comments(APP).count("p3_base64url("), 1, "the only encoding is the checked one")
        f = self.body("static size_t build_frame(")
        self.assertIn('p3_stop(P3_PROTOCOL, "PROTOCOL_FRAME: outbound line too long")', f)

    def test_an_incomplete_observation_and_an_unrendered_block_are_protocol(self):
        b = self.body("static int run_candidate(")
        obs = b.index("if (b3_orch_observe(&O, S.seq, g_tables_u64) != 0)")
        self.assertIn('p3_stop(P3_PROTOCOL, "PROTOCOL_OBSERVE: the orchestrator could not complete the observation")', b[obs:obs + 300])
        blk = b.index("if (!is_baseline && rec.search == NULL)")
        self.assertIn('p3_stop(P3_PROTOCOL, "PROTOCOL_BLOCK: the search block did not render")', b[blk:blk + 200])
        self.assertLess(obs, blk)
        self.assertLess(blk, b.index('emit_record(&rec, "SCORED")'), "no SCORED record before its block is known")

    def test_the_identity_and_the_session_init_refuse_a_wrong_profile_before_any_candidate(self):
        ident = self.body("static int establish_identity(")
        self.assertIn("b3_profile(S.page.seed, S.page.budget, g_pairs_total) == B3_PROFILE_NONE", ident)
        self.assertIn("in.carto_version = B3_CARTO_VERSION;", ident)
        self.assertIn("in.arms = B3_WIRE_ARMS;", ident)
        self.assertIn("in.b1_map_cost = B3_WIRE_B1_MAP_COST;", ident)
        init = self.body("static void b3_session_init(")
        self.assertIn("b3_orch_init(&O, S.page.seed, S.page.budget, g_pairs_total, g_pair_first, g_pair_count,", init)
        self.assertIn('"STOP_PAGE: the identity page\'s session parameters were refused"', init)


