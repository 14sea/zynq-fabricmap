class FakeSerial:
    """The serial handle L6LineReader reads: `in_waiting` and `read(n)`, fed in pieces."""

    def __init__(self):
        self.buf = b""

    def feed(self, b: bytes):
        self.buf += b

    @property
    def in_waiting(self):
        return len(self.buf)

    def read(self, n):
        out, self.buf = self.buf[:n], self.buf[n:]
        return out


class TheHostReadsTheLongestLine(unittest.TestCase):
    def test_the_longest_line_in_pieces_of_every_size_through_the_reader_and_the_parser(self):
        n, lrd = instrument()
        line = driver()["lines"]["MAXLINE"]
        self.assertTrue(line.startswith(f"P3L5 REC 4294967295 {TOKEN} "))
        self.assertEqual(len(line) + 1, app_macro("B3_LINE_MAX") - (len("AUDIT_READY") - len("REC")))
        raw = line.encode()
        for piece in (1, 7, 63, 64, 1000, 4096, len(raw)):
            with self.subTest(piece=piece):
                ser, clock = FakeSerial(), iter(range(10 ** 6))
                rd = lrd.L6LineReader(ser, clock_mono=lambda: next(clock), clock_wall=lambda: 0.0)
                got = []
                for i in range(0, len(raw), piece):
                    ser.feed(raw[i:i + piece])
                    got += [x[0] for x in rd.poll()]
                self.assertEqual(len(got), 1, "one line, however it arrived")
                self.assertEqual(got[0].rstrip("\n"), line.rstrip("\n"))
                self.assertEqual(rd.take_fragments(), [])
                f = n.parse_line(got[0])
                self.assertEqual((f["type"], f["seq"], f["token"]), ("REC", 4294967295, TOKEN))
                rec = n.decode_payload(f["payload"])
                self.assertEqual(rec["seq"], 4294967295)
                self.assertEqual(len(rec["search"]["ledger"]["behaviour_delta"]), 384)
                self.assertEqual(len(rec["search"]["ledger"]["decoded"]), 292)

