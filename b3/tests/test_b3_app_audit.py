"""The B3 application's audit (B3 lifecycle 2, image stage 5, first unit): its outbound buffers against the theoretical
maximum of what their encoders accept, the longest line through the instrument's own host reader and collector, the
fail-closed paths at the source, and the AXI allowlist against the carrier's RTL decode.

Bounds. A host driver GENERATED here (into the top-level build/, never under b3/) links the image's own encoders —
b3_record.c, b3_carto.c, b2_search.c, b3_wire.c, p3_derive.c — and calls each with every member present, every
integer at its widest and every string at the longest length the application can hand it (the longest string literal
of b3_app.c, p3_rectx.c and p3_pull.c — the reasons, the outcomes, the findings — or the fixed length of the hex
buffer it passes), and the O arm's search block at its LARGEST LEGAL ledger (all 384 positions toggled, all 292
addresses decoded at two-digit vectors, the widest counters). The bounds are recomputed from those measurements:
B3_SEARCH_BLOCK_MAX = the largest block + NUL; B3_PAYLOAD_MAX = the largest payload of any type + NUL; B3_ENCODED_MAX =
4 * ceil(payload / 3) + NUL; B3_LINE_MAX = "P3L5 " + the longest frame type + " " + 10 + " " + 32 + " " + the encoding +
" " + 8 + "\\n" + NUL — and b3_app.c must declare exactly those, and size every outbound and resend buffer with them.
Every encoder refuses (0) a buffer exactly its length and renders into one byte more.

The host side. The longest line the application can emit goes through the instrument's L6LineReader (the reader the
B1 / B2 sessions use) in pieces of every size, through l5_notary.parse_line / decode_payload, and — with seq 1 — through
the instrument's Collector; a torn first transmission is quarantined and the resend is the one line that counts.

The fail-closed paths are audited in the source (the dynamic exercise of the application is image stage 6's host
application): an encoder's 0 is PROTOCOL; the base64 capacity is checked BEFORE p3_base64url, which takes none; an
observation the orchestrator cannot complete, and a scored candidate whose block does not render, are PROTOCOL.

The AXI allowlist (the instrument's test_axi_map_vs_rtl, as tests/test_b1_carrier.py ports it): the application's
read and write decode lie inside rtl/b1/b1_axil.v's, the RTL's reads are all the application reads, the only RTL
writes the application lacks are the MAC key window, CTRL is never read and the key window is never named.

No skip: a missing compiler or instrument is a failure.
"""
